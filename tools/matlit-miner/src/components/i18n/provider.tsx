'use client'

import { createContext, useContext, useState, useCallback, useEffect } from 'react'

export type Locale = 'en' | 'zh'

interface I18nContextValue {
  locale: Locale
  setLocale: (l: Locale) => void
  toggle: () => void
  t: (key: string, vars?: Record<string, string | number>) => string
  /** Pick between two literal values based on the current locale. Useful for
   *  data-driven structures (e.g. `pick(en.name, en.nameZh)`) where splitting
   *  every entry into its own i18n key would be impractical. */
  pick: <T,>(en: T, zh: T) => T
}

const I18nContext = createContext<I18nContextValue | null>(null)

const STORAGE_KEY = 'matlit-locale'

export function I18nProvider({ children }: { children: React.ReactNode }) {
  // Lazy init: read from localStorage / navigator on first render to avoid
  // the setState-in-effect lint warning and a flash of the wrong locale.
  const [locale, setLocaleState] = useState<Locale>('en')

  // Hydrate locale from localStorage/navigator after mount (avoids SSR mismatch)
  useEffect(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY) as Locale | null
      if (saved === 'en' || saved === 'zh') {
        setLocaleState(saved)
        return
      }
      const nav = navigator.language?.toLowerCase() ?? ''
      if (nav.startsWith('zh')) setLocaleState('zh')
    } catch {
      // ignore
    }
  }, [])

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l)
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      // ignore
    }
  }, [])

  const toggle = useCallback(() => {
    setLocaleState((prev) => {
      const next = prev === 'en' ? 'zh' : 'en'
      try {
        localStorage.setItem(STORAGE_KEY, next)
      } catch {
        // ignore
      }
      return next
    })
  }, [])

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) =>
      translate(locale, key, vars),
    [locale],
  )

  const pick = useCallback(
    <T,>(en: T, zh: T): T => (locale === 'zh' ? zh : en),
    [locale],
  )

  return (
    <I18nContext.Provider value={{ locale, setLocale, toggle, t, pick }}>
      {children}
    </I18nContext.Provider>
  )
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}

/**
 * Non-hook translation lookup. Use inside plain functions / modules where
 * `useI18n()` can't be called (e.g. the `getPresetStrings(locale)` helper
 * shared by PresetMenu + CustomFilterDialog). Returns the localized string
 * for `key` in `locale`, substituting `{var}` placeholders from `vars`.
 */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dict = locale === 'zh' ? dictZh : dictEn
  let s = dict[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return s
}

