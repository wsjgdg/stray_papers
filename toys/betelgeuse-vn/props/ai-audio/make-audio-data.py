#!/usr/bin/env python3
"""Pack props/ai-audio/*.mp3 into props/audio-data.js (window.VN_AUDIO_ASSETS).

BGM files map to background ids so audio.js's sampled-bed layer picks them
up via VN_AUDIO.scene(bgId); SFX files keep their sfx_ prefixed names.
"""
import base64
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
KEY_MAP = {
    "title": "title",
    "bgm_apartment": "apartment_night",
    "bgm_observatory": "observatory_night",
    "bgm_server": "server_room",
    "bgm_memory": "memory_white",
    "bgm_rain": "streets_rain",
    "bgm_dawn": "dawn_ending",
    "bgm_star": "finale_star",
}

out = [
    "// Generated by ai-audio/make-audio-data.py — do not edit.",
    "// Sampled beds keyed by background id; audio.js prefers these over synth.",
    "window.VN_AUDIO_ASSETS = {",
]
total = 0
packed = 0
names = sorted(
    f.stem for f in HERE.glob("*.mp3")
)
for stem in names:
    key = KEY_MAP.get(stem, stem)
    data = base64.b64encode((HERE / f"{stem}.mp3").read_bytes()).decode()
    total += len(data)
    packed += 1
    out.append(f"  {key}: 'data:audio/mpeg;base64,{data}',")
out.append("};")
(HERE.parent / "audio-data.js").write_text("\n".join(out), encoding="utf-8")
print(f"audio-data.js written: {packed} tracks, base64 payload ~{total // 1024} KB")
