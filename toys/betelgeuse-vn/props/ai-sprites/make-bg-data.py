#!/usr/bin/env python3
"""Pack ai-sprites/bg-*.webp into props/bg-data.js (window.VN_BG_IMG).

Full-bleed background art: downscale to 1280px wide, webp q76 — the engine
paints it as `url(...) center/cover` over the CSS gradient fallback.
"""
import base64
import io
from pathlib import Path

from PIL import Image

DIR = Path(__file__).resolve().parent
BGS = [
    "title",
    "apartment_night",
    "email_screen",
    "streets_rain",
    "observatory_night",
    "server_room",
    "memory_white",
    "dawn_ending",
    "finale_star",
    # scene-named variants (#bg-variants): one unique image per scene,
    # zero reuse — see gen-bg-scenes.sh / gen-bg-variants.sh
    "apartment_night__night_thoughts",
    "email_screen__reply_email",
    "email_screen__ending_silence",
    "email_screen__log_last",
    "observatory_night__diverge",
    "server_room__finale_gate",
    "streets_rain__call_lin",
    "streets_rain__climb_rain",
    "streets_rain__ending_turnback",
    "streets_rain__ending_bad",
    "observatory_night__obsv_daily",
    "observatory_night__converge_talk",
    "observatory_night__keeper_before",
    "observatory_night__gate_approach",
    "observatory_night__wake_check",
    "server_room__hall_quiet",
    "server_room__server_hall",
    "server_room__liar_reveal",
    "server_room__lin_grief",
    "server_room__qi_converse",
    "server_room__cut_path",
    "server_room__substitute_before",
    "server_room__clearance_before",
    "server_room__qi_watch",
    "server_room__qi_dawn",
    "server_room__ending_clearance",
    "server_room__ending_qi",
    "memory_white__wake_path",
    "memory_white__wake_talk",
    "memory_white__old_fight",
    "memory_white__unplug_before",
    "memory_white__ending_unplug",
    "dawn_ending__morning_table",
    "finale_star__ending_substitute",
    "finale_star__extras_1",
    "finale_star__extras_2",
    # gen-bg-final.sh: the last 8 scenes that still reused a base painting
    # (opening / email_first / went_solo / obsv_night / descend /
    #  memory_dive / ending_good / ending_true) — zero-reuse complete
    "apartment_night__opening",
    "email_screen__email_first",
    "streets_rain__went_solo",
    "observatory_night__obsv_night",
    "server_room__descend",
    "memory_white__memory_dive",
    "dawn_ending__ending_good",
    "finale_star__ending_true",
]

out = ["// Generated by ai-sprites/make-bg-data.py — do not edit.",
       "// Full-bleed raster backgrounds; engine layers them over bg.css.",
       "window.VN_BG_IMG = {"]
total = 0
missing = []
for bid in BGS:
    p = DIR / f"bg-{bid}.webp"
    if not p.exists():
        missing.append(bid)
        continue
    img = Image.open(p).convert("RGB")
    if img.width > 1280:
        img = img.resize((1280, round(img.height * 1280 / img.width)), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=76, method=6)
    data = base64.b64encode(buf.getvalue()).decode()
    total += len(data)
    out.append(f"  {bid}: 'data:image/webp;base64,{data}',")
out.append("};")
(DIR.parent / "bg-data.js").write_text("\n".join(out), encoding="utf-8")
if missing:
    print("MISSING:", ", ".join(missing))
print(f"bg-data.js written, base64 payload ~{total // 1024} KB")
