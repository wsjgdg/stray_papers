#!/usr/bin/env python3
"""Pack ai-sprites/bg-*.webp into props/bg-data.js (window.VN_BG_IMG).

Full-bleed background art: downscale to 1280px wide, webp q76 — the engine
paints it as `url(...) center/cover` over the CSS gradient fallback.
"""
import base64
import io
from pathlib import Path

from PIL import Image

DIR = Path(__file__).resolve().parent
BGS = [
    "apartment_night",
    "email_screen",
    "streets_rain",
    "observatory_night",
    "server_room",
    "memory_white",
    "dawn_ending",
    "finale_star",
]

out = ["// Generated by ai-sprites/make-bg-data.py — do not edit.",
       "// Full-bleed raster backgrounds; engine layers them over bg.css.",
       "window.VN_BG_IMG = {"]
total = 0
missing = []
for bid in BGS:
    p = DIR / f"bg-{bid}.webp"
    if not p.exists():
        missing.append(bid)
        continue
    img = Image.open(p).convert("RGB")
    if img.width > 1280:
        img = img.resize((1280, round(img.height * 1280 / img.width)), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=76, method=6)
    data = base64.b64encode(buf.getvalue()).decode()
    total += len(data)
    out.append(f"  {bid}: 'data:image/webp;base64,{data}',")
out.append("};")
(DIR.parent / "bg-data.js").write_text("\n".join(out), encoding="utf-8")
if missing:
    print("MISSING:", ", ".join(missing))
print(f"bg-data.js written, base64 payload ~{total // 1024} KB")
