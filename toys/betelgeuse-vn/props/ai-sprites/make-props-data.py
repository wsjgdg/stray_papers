#!/usr/bin/env python3
"""Rebuild props/props-data.js from ai-sprites/prop-*.webp (AI-keyed, alpha).

Keeps the same VN_PROPS keys the scenario references (crt, mug, ...,
telescope — telescope also feeds the title keyart). Each prop is normalized
to a per-key display height so relative scene sizing (width % in scenario.js)
stays close to the old 3D renders.
"""
import base64
import io
from pathlib import Path

from PIL import Image

DIR = Path(__file__).resolve().parent
OUT_H = {  # normalized asset height px (display width % is set per scene)
    "crt": 620,
    "mug": 360,
    "calendar": 520,
    "keys": 380,
    "umbrella": 640,
    "busstop": 760,
    "telescope": 700,
    "badge": 560,
    "sticky": 440,
}

lines = [
    "// Generated by ai-sprites/make-props-data.py (AI art) — do not edit.",
    "window.VN_PROPS = {",
]
total = 0
missing = []
for key, h in OUT_H.items():
    p = DIR / f"prop-{key}.webp"
    if not p.exists():
        missing.append(key)
        continue
    img = Image.open(p)
    if img.height > h:
        img = img.resize((round(img.width * h / img.height), h), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=82, method=6)
    data = base64.b64encode(buf.getvalue()).decode()
    total += len(data)
    lines.append(f'  "{key}": "data:image/webp;base64,{data}",')
lines.append("};")
(DIR.parent / "props-data.js").write_text("\n".join(lines), encoding="utf-8")
if missing:
    print("MISSING:", ", ".join(missing))
print(f"props-data.js written, base64 payload ~{total // 1024} KB")
