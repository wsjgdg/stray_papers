#!/usr/bin/env python3
"""Pack ai-sprites/*.webp into props/sprites-data.js (window.CHAR_ART_IMG).

Each entry is ready-to-inject markup: <img src="data:image/webp;base64,...">.
沈眠 (mian) keeps her ghostly presence: the img carries the same per-feel
opacity the SVG art applied (.78 sad / .88 otherwise).

Pose A is the standing set keyed plain ("normal"); poses b/c/d/e are keyed
"<pose>_<feel>" from files named "<char>-<pose>-<feel>.webp".

Gaze variants (engine line.gaze "l"/"r") pack "<key>_gl"/"<key>_gr" from
"<char>-a-<feel>-gl|gr.webp" (pose A carries an explicit "a" segment) /
"<char>-<pose>-<feel>-gl|gr.webp" (b..e). "gl" looks toward the viewer's
left, "gr" toward the viewer's right. Absent gaze files are optional.
"""
import base64
import io
from pathlib import Path

from PIL import Image

DIR = Path(__file__).resolve().parent
FEELS = [
    "normal",
    "happy",
    "sad",
    "surprised",
    "angry",
    "worried",
    "shy",
    "cry",
]
CAST = ["yu", "lin", "qi", "mian"]
POSES = ["", "b", "c", "d", "e"]


def pack(p):
    """Downscale to 560px height (2.3x display size) and encode webp base64."""
    img = Image.open(p)
    if img.height > 560:
        img = img.resize((round(img.width * 560 / img.height), 560), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=80, method=6)
    return base64.b64encode(buf.getvalue()).decode()

out = [
    "// Generated by ai-sprites/build-sprites-data.py — do not edit.",
    "// Ready-to-inject raster sprite markup; engine prefers this over CHAR_ART.",
    '// Keys: plain feel = pose A (standing), "<pose>_<feel>" = pose b..e sets.',
    "window.CHAR_ART_IMG = {",
]
total = 0
packed = 0
missing = []
for char in CAST:
    out.append(f"  {char}: {{")
    for pose in POSES:
        pre = f"{pose}_" if pose else ""
        for feel in FEELS:
            key = pre + feel
            # gaze variants key "<key>_gl"/"<key>_gr"; pose A source files carry
            # an explicit "a" segment ("<char>-a-<feel>-gl.webp"), poses b..e
            # match their base naming. Gaze files are optional: absent ones are
            # skipped silently (engine falls back to the center-facing key),
            # only base files report MISSING.
            variants = [
                (
                    key,
                    f"{char}-{pose}-{feel}.webp" if pose else f"{char}-{feel}.webp",
                    True,
                )
            ]
            for sfx in ("gl", "gr"):
                variants.append(
                    (
                        f"{key}_{sfx}",
                        f"{char}-a-{feel}-{sfx}.webp"
                        if not pose
                        else f"{char}-{pose}-{feel}-{sfx}.webp",
                        False,
                    )
                )
            style = (
                ' style="opacity:.78"'
                if (char == "mian" and feel == "sad")
                else ' style="opacity:.88"' if char == "mian" else ""
            )
            for vkey, fname, required in variants:
                p = DIR / fname
                if not p.exists():
                    if required:
                        missing.append(fname)
                    continue
                data = pack(p)
                total += len(data)
                packed += 1
                out.append(
                    f"    {vkey}: "
                    f"'<img src=\"data:image/webp;base64,{data}\" "
                    f'alt="" draggable="false"{style}>\','
                )
    out.append("  },")
out.append("};")
(DIR.parent / "sprites-data.js").write_text("\n".join(out), encoding="utf-8")
if missing:
    print(f"MISSING {len(missing)} files:")
    for m in missing:
        print("  ", m)
print(f"sprites-data.js written: {packed} sprites, base64 payload ~{total // 1024} KB")
