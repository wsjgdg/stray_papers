#!/usr/bin/env python3
"""Pack ai-sprites/*.webp into props/sprites-data.js (window.CHAR_ART_IMG).

Each entry is ready-to-inject markup: <img src="data:image/webp;base64,...">.
沈眠 (mian) keeps her ghostly presence: the img carries the same per-feel
opacity the SVG art applied (.78 sad / .88 otherwise).

Pose A is the standing set keyed plain ("normal"); poses b/c/d/e are keyed
"<pose>_<feel>" from files named "<char>-<pose>-<feel>.webp".
"""
import base64
import io
from pathlib import Path

from PIL import Image

DIR = Path(__file__).resolve().parent
FEELS = [
    "normal",
    "happy",
    "sad",
    "surprised",
    "angry",
    "worried",
    "shy",
    "cry",
]
CAST = ["yu", "lin", "qi", "mian"]
POSES = ["", "b", "c", "d", "e"]

out = [
    "// Generated by ai-sprites/build-sprites-data.py — do not edit.",
    "// Ready-to-inject raster sprite markup; engine prefers this over CHAR_ART.",
    '// Keys: plain feel = pose A (standing), "<pose>_<feel>" = pose b..e sets.',
    "window.CHAR_ART_IMG = {",
]
total = 0
packed = 0
missing = []
for char in CAST:
    out.append(f"  {char}: {{")
    for pose in POSES:
        pre = f"{pose}_" if pose else ""
        for feel in FEELS:
            key = pre + feel
            fname = (
                f"{char}-{pose}-{feel}.webp" if pose else f"{char}-{feel}.webp"
            )
            p = DIR / fname
            if not p.exists():
                missing.append(fname)
                continue
            # downscale to 560px height (2.3x display size) to keep payload tight
            img = Image.open(p)
            if img.height > 560:
                img = img.resize(
                    (round(img.width * 560 / img.height), 560), Image.LANCZOS
                )
            buf = io.BytesIO()
            img.save(buf, "WEBP", quality=80, method=6)
            data = base64.b64encode(buf.getvalue()).decode()
            total += len(data)
            packed += 1
            style = (
                ' style="opacity:.78"'
                if (char == "mian" and feel == "sad")
                else ' style="opacity:.88"' if char == "mian" else ""
            )
            out.append(
                f"    {key}: "
                f"'<img src=\"data:image/webp;base64,{data}\" "
                f'alt="" draggable="false"{style}>\','
            )
    out.append("  },")
out.append("};")
(DIR.parent / "sprites-data.js").write_text("\n".join(out), encoding="utf-8")
if missing:
    print(f"MISSING {len(missing)} files:")
    for m in missing:
        print("  ", m)
print(f"sprites-data.js written: {packed} sprites, base64 payload ~{total // 1024} KB")
