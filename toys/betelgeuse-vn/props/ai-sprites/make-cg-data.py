#!/usr/bin/env python3
"""Pack ai-sprites/cg-*.webp into props/cg-data.js (window.VN_CG_IMG).

Story CGs: 1280px wide webp q80 — full-bleed 16:9 event illustrations the
engine overlays via line.cg.
"""
import base64
import io
from pathlib import Path

from PIL import Image

DIR = Path(__file__).resolve().parent
CGS = ["cg_memory", "cg_archive", "cg_dawn"]

out = ["// Generated by ai-sprites/make-cg-data.py — do not edit.",
       "// Full-screen story CGs; shown via line.cg / cleared with line.cg:null.",
       "window.VN_CG_IMG = {"]
total = 0
missing = []
for cid in CGS:
    p = DIR / f"{cid}.webp"
    if not p.exists():
        missing.append(cid)
        continue
    img = Image.open(p).convert("RGB")
    if img.width > 1280:
        img = img.resize((1280, round(img.height * 1280 / img.width)), Image.LANCZOS)
    buf = io.BytesIO()
    img.save(buf, "WEBP", quality=80, method=6)
    data = base64.b64encode(buf.getvalue()).decode()
    total += len(data)
    out.append(f"  {cid}: 'data:image/webp;base64,{data}',")
out.append("};")
(DIR.parent / "cg-data.js").write_text("\n".join(out), encoding="utf-8")
if missing:
    print("MISSING:", ", ".join(missing))
print(f"cg-data.js written, base64 payload ~{total // 1024} KB")
