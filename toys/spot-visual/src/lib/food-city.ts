export interface CityFood {
  /** 展示简称 */
  label: string;
  /** 行政区全称 */
  fullName: string;
  /** 代表菜 */
  dish: string;
  /** 菜系 */
  cuisine: string;
  /** 说明 */
  desc: string;
  /** true = 该城市有专属名食；false = 沿用省域代表菜 */
  isLocal: boolean;
}

/** 城市 → 代表菜：先查覆盖表，未命中则回退省域风味并标注 */
export function resolveCityFood(province: ProvinceFood, fullName: string): CityFood {
  const label = cityLabel(fullName);
  const over = lookupCityOverride(fullName);
  if (over) {
    return {
      label,
      fullName,
      dish: over.dish,
      cuisine: over.cuisine ?? province.cuisine,
      desc: over.desc,
      isLocal: true,
    };
  }
  return {
    label,
    fullName,
    dish: province.dish,
    cuisine: province.cuisine,
    desc: `该市暂无单独收录的地方名食，此处沿用${province.fullName}省域代表菜「${province.dish}」。${province.desc}`,
    isLocal: false,
  };
}
