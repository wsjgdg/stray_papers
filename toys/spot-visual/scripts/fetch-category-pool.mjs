/**
 * 分类图片池离线化：把 spot-data.ts 里 CATEGORY_PHOTOS / FALLBACK_PHOTOS 的
 * Unsplash CDN 远程 URL 下载为本地 webp，生成 URL → 本地路径映射。
 *
 * 为什么：无 API key 环境（本地池是最后一道有图降级）+ 断网演示时，
 * 远程池 URL 同样开天窗；下载一次（约 2MB）让降级链完全离线。
 *
 * 用法：node scripts/fetch-category-pool.mjs（跳过已下载的，可断点续跑）
 * 产出：public/spots/pool/*.webp + src/lib/category-pool.generated.ts
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";
import { execFileSync } from "node:child_process";

const OUT_DIR = path.resolve("public/spots/pool");
const GEN_FILE = path.resolve("src/lib/category-pool.generated.ts");
const SRC = fs.readFileSync("src/lib/spot-data.ts", "utf8");

const urls = [
  ...new Set(
    [...SRC.matchAll(/https:\/\/images\.unsplash\.com\/[^"']+/g)].map(
      (m) => m[0],
    ),
  ),
];
console.log(`池 URL 共 ${urls.length} 条`);

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) Chrome/141.0 Safari/537.36";
function curl(url) {
  return execFileSync("curl", ["-sS", "-m", "30", "-L", "-A", UA, url], {
    encoding: "buffer",
    maxBuffer: 64 * 1024 * 1024,
  });
}

fs.mkdirSync(OUT_DIR, { recursive: true });
const map = {};
let ok = 0,
  fail = 0;
for (const url of urls) {
  const photoId = url.match(/photo-([^?/]+)/)?.[1] ?? crypto.randomUUID();
  const out = path.join(OUT_DIR, `photo-${photoId}.webp`);
  if (fs.existsSync(out)) {
    map[url] = `/spots/pool/${path.basename(out)}`;
    ok++;
    continue;
  }
  try {
    const buf = curl(
      `${url}${url.includes("?") ? "&" : "?"}w=640&q=75&fit=crop`,
    );
    if (buf.length < 5000) throw new Error(`too small ${buf.length}B`);
    await sharp(buf).webp({ quality: 78 }).toFile(out);
    map[url] = `/spots/pool/${path.basename(out)}`;
    ok++;
    console.log(`✓ ${photoId}  ${(buf.length / 1024).toFixed(0)}KB`);
  } catch (e) {
    fail++;
    console.log(`✗ ${url.slice(30, 70)}  ${e.message}`);
  }
}

const ts = `// GENERATED by scripts/fetch-category-pool.mjs — 分类池远程 URL 的本地离线副本
// 不要手改；重跑 npm run pool:fetch 重新生成。
export const POOL_LOCAL: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;
fs.writeFileSync(GEN_FILE, ts, "utf8");
console.log(
  `\n${ok}/${urls.length} 离线化，${fail} 失败 → ${path.basename(GEN_FILE)}`,
);
if (fail > 0) process.exitCode = 1;
