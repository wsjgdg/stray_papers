/**
 * 构建时烘「景点服务设施」数据：腾讯位置服务 nearby 搜索（厕所/出口）
 * → src/lib/scenic-services.generated.ts。key 只在本机 .env，绝不进产物。
 *
 * 为什么用腾讯不用高德：高德配额已耗尽；腾讯位置服务的 POI 搜索可按
 * 「公共厕所」「出口」检索，返回真实坐标，可算 haversine 最近距离。
 *
 * 用法：node scripts/fetch-scenic-services.mjs [级别5A|4A]（默认 5A；限流 3 QPS）
 * 增量落盘 + 原子写（与 fetch-scenic-details 同模式）。
 * 产物字段：toiletCount / nearestToiletM / exitCount / nearestExitM
 */
import fs from "node:fs";
import path from "node:path";

const KEY =
  process.env.TENCENT_KEY ||
  (() => {
    for (const p of ["C:/Users/sibop/.secrets/map.env", path.resolve(".env")]) {
      if (!fs.existsSync(p)) continue;
      const m = fs.readFileSync(p, "utf8").match(/^TENCENT_KEY=(.+)$/m);
      if (m) return m[1].trim();
    }
    return "";
  })();
if (!KEY) {
  console.error("缺少 TENCENT_KEY");
  process.exit(1);
}

const LEVEL = process.argv[2] === "4A" ? "4A" : "5A";
const OUT_TS = path.resolve("src/lib/scenic-services.generated.ts");
const CACHE = path.resolve("scripts/scenic-services.cache.json");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// ── 从生成的 TS 里解析 EXTRA_SCENICS ──
const src = fs.readFileSync(
  path.resolve("src/lib/scenic-enrich.generated.ts"),
  "utf8",
);
const blocks = src
  .slice(src.indexOf("EXTRA_SCENICS"))
  .split(/\{\s*"name":/)
  .slice(1)
  .map((b) => ({
    name: b.match(/^\s*"([^"]+)"/)?.[1] ?? "",
    city: b.match(/"city": "([^"]+)"/)?.[1] ?? "",
    lng: Number(b.match(/"lng": ([\d.]+)/)?.[1] ?? 0),
    lat: Number(b.match(/"lat": ([\d.]+)/)?.[1] ?? 0),
    level: b.match(/"level": "([^"]+)"/)?.[1] ?? "",
  }))
  .filter((e) => e.name && e.level === LEVEL && e.lng && e.lat);
console.log(`${LEVEL} 条目: ${blocks.length}`);

// ── 缓存（独立 JSON，prettier 不碰）──
const existing = fs.existsSync(CACHE)
  ? JSON.parse(fs.readFileSync(CACHE, "utf8"))
  : {};
console.log(`已有缓存: ${Object.keys(existing).length}`);

const results = { ...existing };
let hit = 0;
let miss = 0;

// haversine（米）
function distM(lng1, lat1, lng2, lat2) {
  const R = 6371000;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLng = ((lng2 - lng1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLng / 2) ** 2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
}

// 原子写
function flush() {
  const normalized = Object.fromEntries(Object.entries(results).map(([k, v]) => [k, v]));
  fs.writeFileSync(CACHE, JSON.stringify(normalized, null, 2));
  const banner = `// GENERATED by scripts/fetch-scenic-services.mjs — 景区周边服务设施（腾讯位置服务，构建时烘焙）
// key 只在本机 .env，绝不进产物。toiletCount/nearestToiletM 来自 nearby 厕所搜索；exitCount/nearestExitM 来自 nearby 出口搜索。
export interface ScenicServices {
  toiletCount: number;
  nearestToiletM: number;
  exitCount: number;
  nearestExitM: number;
}

`;
  const body = `export const SCENIC_SERVICES: Record<string, ScenicServices> = ${JSON.stringify(normalized, null, 2)};\n`;
  const tmp = OUT_TS + ".tmp";
  fs.writeFileSync(tmp, banner + body, "utf8");
  fs.renameSync(tmp, OUT_TS);
}

// 腾讯 nearby 搜索
async function searchNearby(kw, lng, lat, radius) {
  const url =
    `https://apis.map.qq.com/ws/place/v1/search?keyword=${encodeURIComponent(kw)}` +
    `&boundary=nearby(${lat},${lng},${radius},1)&key=${KEY}&page_size=20`;
  const res = await fetch(url, { signal: AbortSignal.timeout(8000) });
  const j = await res.json();
  if (j.status !== 0) throw new Error(j.message || `status ${j.status}`);
  return j.data ?? [];
}

async function fetchServices(e, pass) {
  // pass 1: 厕所（500m）；pass 2: 出口（300m）
  const conf =
    pass === 0
      ? { kw: "公共厕所", radius: 500, filter: /厕所|洗手间|卫生间/ }
      : { kw: "出口", radius: 300, filter: /出口|入口|大门|门/ };
  try {
    const pois = await searchNearby(conf.kw, e.lng, e.lat, conf.radius);
    let nearest = Infinity;
    let count = 0;
    for (const p of pois) {
      const d = distM(e.lng, e.lat, p.location.lng, p.location.lat);
      if (d > (pass === 0 ? 800 : 500)) continue;
      count++;
      if (d < nearest) nearest = d;
    }
    return { count, nearest: nearest === Infinity ? null : Math.round(nearest) };
  } catch {
    return null;
  }
}

for (let i = 0; i < blocks.length; i++) {
  const e = blocks[i];
  if (results[e.name]) continue;
  const toiletRes = await fetchServices(e, 0);
  await sleep(200);
  const exitRes = await fetchServices(e, 1);
  if (toiletRes && exitRes) {
    results[e.name] = {
      toiletCount: toiletRes.count,
      nearestToiletM: toiletRes.nearest ?? -1,
      exitCount: exitRes.count,
      nearestExitM: exitRes.nearest ?? -1,
    };
    hit++;
  } else {
    miss++;
    if (miss <= 5) console.log(`  MISS ${e.name}`);
  }
  if ((i + 1) % 50 === 0) {
    flush();
    console.log(`进度 ${i + 1}/${blocks.length} 命中 ${hit} 未中 ${miss}`);
  }
  await sleep(200);
}

flush();
console.log(
  `完成：命中 ${hit}，未中 ${miss}，总 ${Object.keys(results).length} → ${OUT_TS}`,
);
