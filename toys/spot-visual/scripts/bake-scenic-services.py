# 从 OSM POI 坐标为每个 A 级景区算最近厕所/出入口距离 → scenic-services.generated.ts
# 读取 data/osm-toilets-gates.json + scenic-enrich.generated.ts → 输出按 spotName 键控
import json
import math
import re

def haversine_m(lng1, lat1, lng2, lat2):
    R = 6371000
    dLat = math.radians(lat2 - lat1)
    dLng = math.radians(lng2 - lng1)
    a = (math.sin(dLat / 2) ** 2 +
         math.cos(math.radians(lat1)) * math.cos(math.radians(lat2)) * math.sin(dLng / 2) ** 2)
    return R * 2 * math.atan2(math.sqrt(a), math.sqrt(1 - a))

# 1) 读 OSM POI
with open("data/osm-toilets-gates.json", encoding="utf-8") as f:
    osm = json.load(f)
toilets = osm["toilets"]
gates = osm["gates"]
print(f"OSM POI: toilets={len(toilets)} gates={len(gates)}")

# 2) 解析 scenic spots
src = open("src/lib/scenic-enrich.generated.ts", encoding="utf-8").read()
start = src.index("EXTRA_SCENICS")
blocks = re.split(r'\{\s*"name":', src[start:])[1:]
spots = []
for b in blocks:
    m = re.match(r'\s*"([^"]+)"', b)
    if not m:
        continue
    name = m.group(1)
    lng_m = re.search(r'"lng": ([\d.]+)', b)
    lat_m = re.search(r'"lat": ([\d.]+)', b)
    level_m = re.search(r'"level": "([^"]+)"', b)
    if lng_m and lat_m and level_m:
        spots.append({
            "name": name,
            "lng": float(lng_m.group(1)),
            "lat": float(lat_m.group(1)),
            "level": level_m.group(1),
        })
print(f"scenic spots: {len(spots)}")

# 3) 网格索引加速最近邻
CELL = 0.1
def build_grid(pois):
    grid = {}
    for lng, lat in pois:
        key = (int(lng / CELL), int(lat / CELL))
        grid.setdefault(key, []).append((lng, lat))
    return grid

def nearest(grid, lng, lat):
    gx, gy = int(lng / CELL), int(lat / CELL)
    best_d = float("inf")
    for dx in range(-1, 2):
        for dy in range(-1, 2):
            for p in grid.get((gx + dx, gy + dy), []):
                d = haversine_m(lng, lat, p[0], p[1])
                if d < best_d:
                    best_d = d
    return best_d

toilet_grid = build_grid(toilets)
gate_grid = build_grid(gates)

results = {}
no_toilet = 0
no_exit = 0
for s in spots:
    # 最近厕所
    td = nearest(toilet_grid, s["lng"], s["lat"])
    has_toilet = td < float("inf")
    # 最近出口
    gd = nearest(gate_grid, s["lng"], s["lat"])
    has_exit = gd < float("inf")
    results[s["name"]] = {
        "toiletCount": 1 if has_toilet else 0,
        "nearestToiletM": round(td) if has_toilet else -1,
        "exitCount": 1 if has_exit else 0,
        "nearestExitM": round(gd) if has_exit else -1,
    }
    if not has_toilet:
        no_toilet += 1
    if not has_exit:
        no_exit += 1

print(f"结果: {len(results)} 条 | 无厕所: {no_toilet} | 无出口: {no_exit}")

# 4) 写 generated file
banner = """// GENERATED by scripts/bake-scenic-services.py — 景区服务设施（OSM PBF 离线解析，构建时烘焙）
// 数据源：data/osm-toilets-gates.json（从 china.pbf 提取的全国厕所+出入口坐标）
// nearestToiletM/nearestExitM = haversine 最近距离（米）；-1 = 搜索范围内无结果
export interface ScenicServices {
  toiletCount: number;
  nearestToiletM: number;
  exitCount: number;
  nearestExitM: number;
}

"""
body = "export const SCENIC_SERVICES: Record<string, ScenicServices> = " + json.dumps(results, indent=2, ensure_ascii=False) + ";\n"
with open("src/lib/scenic-services.generated.ts", "w", encoding="utf-8") as f:
    f.write(banner + body)
print(f"→ src/lib/scenic-services.generated.ts")
