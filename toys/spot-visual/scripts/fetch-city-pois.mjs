/**
 * 构建时烘城市 POI 包：高德 place/text（types=110000 风景名胜）× 热门城市
 * → src/lib/city-pois.generated.ts 入库。key 只在本机 .env 用，绝不进产物。
 *
 * 发布约束：应用不挂任何 key，运行时零外部 POI 调用；数据过期后本机重跑即可刷新。
 * 用法：node scripts/fetch-city-pois.mjs [城市...]（默认全部 CITIES；限流 3 QPS，自带 sleep）
 */
import fs from "node:fs";
import path from "node:path";

const KEY =
  process.env.AMAP_KEY ||
  (() => {
    for (const p of ["C:/Users/sibop/.secrets/map.env", path.resolve(".env")]) {
      if (!fs.existsSync(p)) continue;
      const m = fs.readFileSync(p, "utf8").match(/^AMAP_KEY=(.+)$/m);
      if (m) return m[1].trim();
    }
    return "";
  })();
if (!KEY) {
  console.error("缺少 AMAP_KEY（.env 或 C:/Users/sibop/.secrets/map.env）");
  process.exit(1);
}

const CITIES = [
  "北京", "上海", "广州", "深圳", "杭州", "南京", "苏州", "成都", "重庆", "西安",
  "洛阳", "武汉", "长沙", "厦门", "青岛", "大连", "昆明", "桂林", "三亚", "哈尔滨",
];
const PER_CITY = 15;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// type 字符串 → 项目分类（对齐 spot-data 的分类体系）
function inferCategory(type = "", name = "") {
  const t = type + name;
  if (/博物馆|纪念馆|文物|古迹|遗址|陵|故居|会馆|宫殿/.test(t)) return "历史人文";
  if (/寺|庙|观$|庵|塔|教堂|清真/.test(t)) return "宗教寺庙";
  if (/古镇|古城|古村|老街|古街/.test(t)) return "古镇村落";
  if (/乐园|游乐|主题公园|影城|动物园|植物园/.test(t)) return "主题乐园";
  if (/山|峰|岭|湖|江|河|瀑布|峡谷|溶洞|森林|草原|泉|滩|湾|岛/.test(t)) return "自然风光";
  if (/公园|广场|步行街|街区|地标|塔|桥/.test(t)) return "城市地标";
  if (/海滨|浴场|海岸/.test(t)) return "海滨度假";
  return "城市地标";
}

function dedupeAddress(p) {
  const parts = [p.pname, p.cityname === p.pname ? "" : p.cityname, p.adname === p.cityname ? "" : p.adname, p.address]
    .filter(Boolean);
  // 去掉连续重复段（如 "浙江省浙江省"）
  const out = [];
  for (const seg of parts) if (out[out.length - 1] !== seg) out.push(seg);
  return out.join("");
}

const packs = {};
let total = 0;

for (const city of CITIES) {
  const collected = new Map(); // name -> poi
  for (let page = 1; page <= 2 && collected.size < PER_CITY + 10; page++) {
    const url =
      `https://restapi.amap.com/v3/place/text?key=${KEY}` +
      `&keywords=景点&types=110000&city=${encodeURIComponent(city)}&citylimit=true` +
      `&offset=25&page=${page}&extensions=base`;
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(15000) });
      const j = await res.json();
      if (j.infocode !== "10000") {
        console.log(`✗ ${city} p${page}: infocode ${j.infocode} ${j.info || ""}`);
        break;
      }
      for (const p of j.pois ?? []) {
        if (!p.name || !p.location) continue;
        const [lng, lat] = p.location.split(",").map(Number);
        if (!Number.isFinite(lng) || !Number.isFinite(lat)) continue;
        if (!collected.has(p.name)) collected.set(p.name, p);
      }
    } catch (e) {
      console.log(`✗ ${city} p${page}: ${e.message}`);
    }
    await sleep(350); // 免费配额 3 QPS
  }
  const rating = (p) => Number(p.biz_ext?.rating) || 0;
  const pois = [...collected.values()]
    .sort((a, b) => rating(b) - rating(a))
    .slice(0, PER_CITY)
    .map((p) => {
      const [lng, lat] = p.location.split(",").map(Number);
      return {
        name: p.name.replace(/(\(\w+\)|（\S+）)$/, ""), // 去掉括号分店/分号后缀
        address: dedupeAddress(p),
        lng,
        lat,
        category: inferCategory(p.type, p.name),
        rating: rating(p) || undefined,
        image: p.photos?.find((x) => x.url)?.url || "",
      };
    });
  if (pois.length > 0) {
    packs[city] = pois;
    total += pois.length;
    console.log(`✓ ${city}: ${pois.length} 个 POI`);
  } else {
    console.log(`✗ ${city}: 0`);
  }
}

const ts = `// GENERATED by scripts/fetch-city-pois.mjs — 高德 POI 构建时烘焙的城市包
// 数据来源：高德地图开放平台（构建日期 ${new Date().toISOString().slice(0, 10)}），仅作演示用途。
// 不要手改；本机重跑 node scripts/fetch-city-pois.mjs 即可刷新（key 不入库）。
export interface CityPoi {
  name: string;
  address: string;
  lng: number;
  lat: number;
  category: string;
  rating?: number;
  image: string;
}

export const CITY_POI_PACKS: Record<string, CityPoi[]> = ${JSON.stringify(packs, null, 2)};
`;
fs.writeFileSync(path.resolve("src/lib/city-pois.generated.ts"), ts, "utf8");
console.log(`\n${Object.keys(packs).length} 城 / ${total} POI → src/lib/city-pois.generated.ts`);
