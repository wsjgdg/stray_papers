/**
 * 构建时烘 5A 名录条目的详情：高德 place/around（按已知坐标附近搜同名 POI）
 * → src/lib/scenic-details.generated.ts。key 只在本机 .env 用，绝不进产物。
 *
 * 为什么 around 而不是 text：名录名（如「八达岭长城风景名胜区」）与高德 POI 名
 * （「八达岭长城」）不完全一致，但 extras 自带坐标 —— 5km 内搜同名 POI，
 * 命中即取评分最高（名称重合度 + 距离 <15km 双重校验），基本不会张冠李戴。
 *
 * 用法：node scripts/fetch-scenic-details.mjs [级别5A|4A]（默认 5A；限流 3 QPS）
 * 产物字段：tel / openTime / image（高德官方图，运行时挂了走本地分类池降级）
 */
import fs from "node:fs";
import path from "node:path";

const KEY =
  process.env.AMAP_KEY ||
  (() => {
    for (const p of ["C:/Users/sibop/.secrets/map.env", path.resolve(".env")]) {
      if (!fs.existsSync(p)) continue;
      const m = fs.readFileSync(p, "utf8").match(/^AMAP_KEY=(.+)$/m);
      if (m) return m.trim ? m[1].trim() : m[1];
    }
    return "";
  })();
if (!KEY) {
  console.error("缺少 AMAP_KEY");
  process.exit(1);
}

const LEVEL = process.argv[2] === "4A" ? "4A" : "5A";
const OUT = path.resolve("src/lib/scenic-details.generated.ts");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// ── 从生成的 TS 里正则解析 EXTRA_SCENICS（机器生成，格式稳定）──
const src = fs.readFileSync(
  path.resolve("src/lib/scenic-enrich.generated.ts"),
  "utf8",
);
const arrStart = src.indexOf("EXTRA_SCENICS");
const blocks = src
  .slice(arrStart)
  .split(/\{\s*"name":/)
  .slice(1)
  .map((b) => ({
    // 切分符已吃掉前缀 `{"name":`，名字是块开头被引号包的第一段
    name: b.match(/^\s*"([^"]+)"/)?.[1] ?? "",
    city: b.match(/"city": "([^"]+)"/)?.[1] ?? "",
    lng: Number(b.match(/"lng": ([\d.]+)/)?.[1] ?? 0),
    lat: Number(b.match(/"lat": ([\d.]+)/)?.[1] ?? 0),
    level: b.match(/"level": "([^"]+)"/)?.[1] ?? "",
  }))
  .filter((e) => e.name && e.level === LEVEL && e.lng && e.lat);
console.log(`${LEVEL} 条目: ${blocks.length}`);

// ── 名称重合度：去掉通用后缀后按字符重合计算 ──
const strip = (s) =>
  s
    .replace(
      /(风景名胜区|旅游度假|旅游区|风景区|景区|旅游区|名胜区|度假区|地址公园|地质公园|森林公园|湿地公园)/g,
      "",
    )
    .replace(/[（(].*[)）]/g, "");
function nameScore(listed, poi) {
  const a = strip(listed);
  const b = strip(poi);
  if (!a || !b) return 0;
  if (a.includes(b) || b.includes(a)) return 1;
  // 公共字符占比
  const setB = new Set(b);
  const hit = [...new Set(a)].filter((ch) => setB.has(ch)).length;
  return hit / Math.max(new Set(a).size, 1);
}

// 缓存放独立 JSON：generated TS 会被 prettier 去掉中文键引号，不能当 JSON 解析
const CACHE = path.resolve("scripts/scenic-details.cache.json");
const existing = fs.existsSync(CACHE)
  ? JSON.parse(fs.readFileSync(CACHE, "utf8"))
  : {};
console.log(`已有缓存: ${Object.keys(existing).length}`);

const results = { ...existing };
let hit = 0,
  miss = 0;

// 两轮策略：先严（types 风景名胜 + 5km），再松（无类型 + 8km）兜底
const PASSES = [
  { types: "&types=110000|110101|110105|110203", radius: 5000 },
  { types: "", radius: 8000 },
];

for (let pass = 0; pass < PASSES.length; pass++) {
  const { types, radius } = PASSES[pass];
  for (let i = 0; i < blocks.length; i++) {
    const e = blocks[i];
    if (results[e.name]) continue;
    const url =
      `https://restapi.amap.com/v3/place/around?key=${KEY}` +
      `&location=${e.lng},${e.lat}&radius=${radius}&keywords=${encodeURIComponent(strip(e.name) || e.name)}` +
      `${types}&offset=6&page=1&extensions=all`;
    let pois = [];
    try {
      const res = await fetch(url);
      const j = await res.json();
      if (j.status === "1") pois = j.pois ?? [];
      else console.log(`  [${i}] API 错误: ${j.info}`);
    } catch (err) {
      console.log(`  [${i}] 请求失败: ${err}`);
    }

    let best = null;
    let bestScore = 0;
    for (const p of pois) {
      const plng = Number(p.location?.split(",")[0]);
      const plat = Number(p.location?.split(",")[1]);
      if (!plng || !plat) continue;
      const dkm = Math.hypot((plng - e.lng) * 85, (plat - e.lat) * 111) * 1.2;
      if (dkm > 15) continue;
      const s = nameScore(e.name, p.name) * (1 - Math.min(dkm, 10) / 40);
      if (s > bestScore) {
        bestScore = s;
        best = { p, dkm };
      }
    }

    if (best && bestScore >= 0.55) {
      const p = best.p;
      const img = p.photos?.[0]?.url ?? "";
      results[e.name] = {
        tel: p.tel || "",
        openTime: p.biz_ext?.opentime2 || p.biz_ext?.opentime || "",
        image: img.startsWith("http") ? img : "",
        match: Math.round(bestScore * 100) / 100,
      };
      hit++;
    } else {
      miss++;
      if (miss <= 10)
        console.log(`  MISS ${e.name}（best=${bestScore.toFixed(2)}）`);
    }
    // 增量落盘：后台运行可能被超时截断，每 40 条持久化一次，重跑即续传
    if ((i + 1) % 40 === 0) flush();
    if ((i + 1) % 25 === 0)
      console.log(
        `pass${pass + 1} 进度 ${i + 1}/${blocks.length} 命中 ${hit} 未中 ${miss}`,
      );
    await sleep(360);
  }
}

// ── 写盘：缓存 JSON + 生成 TS（banner 函数声明提升，增量 flush 可提前调用）──
function banner() {
  return `// GENERATED by scripts/fetch-scenic-details.mjs — 5A/4A 名录条目 × 高德 around 搜索（构建时烘焙）
// key 只在本机 .env，绝不进产物；image 为高德官方图 URL，运行时不可达走本地分类池降级。
export interface ScenicDetail {
  tel: string;
  openTime: string;
  image: string;
  match: number;
}

`;
}
// 高德个别字段回数组（tel/biz_ext），统一拍平成字符串（函数声明提升，增量 flush 可提前调用）
function str(v) {
  return Array.isArray(v) ? v.filter(Boolean).join("; ") : String(v ?? "");
}
function flush() {
  fs.writeFileSync(
    CACHE,
    JSON.stringify(
      Object.fromEntries(
        Object.entries(results).map(([k, v]) => [
          k,
          {
            tel: str(v.tel),
            openTime: str(v.openTime),
            image: str(v.image),
            match: v.match,
          },
        ]),
      ),
      null,
      2,
    ),
  );
  const normalized = JSON.parse(fs.readFileSync(CACHE, "utf8"));
  const body = `export const SCENIC_DETAILS: Record<string, ScenicDetail> = ${JSON.stringify(normalized, null, 2)};\n`;
  fs.writeFileSync(OUT, banner() + body, "utf8");
}
flush();
console.log(
  `完成：命中 ${hit}，未中 ${miss}，总 ${Object.keys(results).length} → ${OUT}`,
);
