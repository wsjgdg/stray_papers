/**
 * 内置景点离线图包：从 public/spots/_candidates/ 选图 → 压缩 webp → 生成清单
 *
 * 选图规则（无人工介入时的确定性筛选，终检用 contact sheet）：
 *   1. 按 _report.json 的来源 URL 过滤：水印图库（千图/588ku/花瓣等）直接剔除；
 *   2. 白名单域名（携程/知乎/搜狐/新浪/新华网/太平洋电脑/中关村/本地宝/去哪儿/官网）优先；
 *   3. sharp 实测宽度 ≥ 600px（冷门景区退档到 ≥ 420px，见下方 MIN_W_FALLBACK）；
 *   4. 每个景点取排序最优的一张，压成 640px/q78 webp → public/spots/<景点名>.webp；
 *   5. 生成 src/lib/spot-photos.generated.ts（景点名 → 本地路径）。
 *
 * 用法：node scripts/build-spot-photos.mjs [--sheet]（--sheet 额外输出候选拼图供人工终检）
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const CAND_DIR = path.resolve("public/spots/_candidates");
const OUT_DIR = path.resolve("public/spots");
const GEN_FILE = path.resolve("src/lib/spot-photos.generated.ts");

const BAD =
  /588ku|qiantucdn|huaban|nipic|tukuppt|58pic|veer|hellorf|vcg|699pic|dfic|gaoding|ibaotu/i;
// 排序权重：越靠前越优先（OTA 官方图/内容平台实拍 > 论坛图）
const PREFERRED = [
  { re: /c-ctrip\.com|ctrip\.com/, s: 30 },
  { re: /mafengwo/, s: 30 },
  { re: /cantontower\.com|official|gov\.cn/, s: 28 },
  { re: /zhimg\.com/, s: 24 },
  { re: /(sohu|163|qq)\.(com|net)|sinaimg\.cn/, s: 20 },
  { re: /xinhuanet|people\.com\.cn/, s: 20 },
  { re: /pconline|zol-img|bendibao/, s: 14 },
  { re: /qunarzz\.com/, s: 12 },
];

function score(url) {
  for (const p of PREFERRED) if (p.re.test(url)) return p.s;
  return 0;
}

async function main() {
  const report = JSON.parse(
    fs.readFileSync(path.join(CAND_DIR, "_report.json"), "utf8"),
  );
  const bySpot = new Map();
  for (const it of report) {
    if (BAD.test(it.image || "")) continue;
    const arr = bySpot.get(it.dish) || [];
    arr.push({ ...it, s: score(it.image || "") });
    bySpot.set(it.dish, arr);
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const manifest = {};
  const skipped = [];

  // 人工终检剔除名单：脚本只按域名/宽度筛，判断不了「这张图是不是这个景区」。
  // 终检结果写进 _rejected.json（[{name, reason}]），烘焙时跳过并清掉旧图，
  // 否则下一次重跑会把刚删掉的图从 _candidates 里又烘回来。
  const REJECT_FILE = path.join(OUT_DIR, "_rejected.json");
  const rejected = new Map(
    (fs.existsSync(REJECT_FILE)
      ? JSON.parse(fs.readFileSync(REJECT_FILE, "utf8"))
      : []
    ).map((r) => [r.name, r.reason ?? ""]),
  );

  for (const [spot, items] of [...bySpot.entries()].sort((a, b) =>
    a[0].localeCompare(b[0], "zh"),
  )) {
    items.sort((a, b) => b.s - a.s);
    if (rejected.has(spot)) {
      const stale = path.join(
        OUT_DIR,
        `${spot.replace(/[/\\:*?"<>|]/g, "-")}.webp`,
      );
      if (fs.existsSync(stale)) fs.unlinkSync(stale);
      console.log(`✗ ${spot} 终检剔除（${rejected.get(spot) || "见 _rejected.json"}）`);
      continue;
    }
    // 两档门槛：先找 ≥600px 的清晰图；都没有时退而接受 ≥420px
    // （输出是 640px 卡片缩略图，420px 源轻微放大可接受，总比整条落渐变占位好；
    //  2026-10-29 加：一批冷门 4A 景区全网只有 400–600px 的图，被单档 600 全数挡掉）
    const MIN_W_STRICT = 600;
    const MIN_W_FALLBACK = 420;
    let picked = null;
    for (const minW of [MIN_W_STRICT, MIN_W_FALLBACK]) {
      for (const it of items) {
        const file = path.join(CAND_DIR, path.basename(it.file));
        try {
          const m = await sharp(file).metadata();
          if ((m.width ?? 0) >= minW) {
            picked = { it, file };
            break;
          }
        } catch {
          /* unreadable, try next */
        }
      }
      if (picked) break;
    }
    if (!picked) {
      skipped.push(spot);
      continue;
    }
    // 文件名安全化：名录里有「扬州市中国雕版印刷博物馆/扬州博物馆」这类带路径分隔符的名字，
    // 直接当文件名会 ENOENT 中断整批。清单键保留原名，只把落盘名安全化。
    const safeSpot = spot.replace(/[/\\:*?"<>|]/g, "-");
    const out = path.join(OUT_DIR, `${safeSpot}.webp`);
    await sharp(picked.file)
      .resize({ width: 640, withoutEnlargement: true })
      .webp({ quality: 78 })
      .toFile(out);
    manifest[spot] = `/spots/${encodeURIComponent(safeSpot)}.webp`;
    console.log(
      `✓ ${spot} ← ${path.basename(picked.file)} (${picked.it.s}分, ${picked.it.image.slice(8, 50)}…)`,
    );
  }

  if (skipped.length) {
    console.warn(`⚠ 未选到合格图（需补抓或人工挑）: ${skipped.join("、")}`);
  }

  const ts = `// GENERATED by scripts/build-spot-photos.mjs — 内置景点离线图包（Bing 抓取，来源见 public/spots/_candidates/_report.json）
// 不要手改；重跑 npm run spots 重新生成。
export const SPOT_PHOTOS: Record<string, string> = ${JSON.stringify(manifest, null, 2)};
`;
  fs.writeFileSync(GEN_FILE, ts, "utf8");
  console.log(
    `\n共 ${Object.keys(manifest).length} 张 → public/spots/，清单 → src/lib/spot-photos.generated.ts`,
  );
}

main();
