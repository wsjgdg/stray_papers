/**
 * top240 POI 首图本地化：与 poi-descriptions.ts 同名单（每城评分 top12），
 * 下载高德 CDN 首图 → sharp 压 640px webp → public/spots/pois/，
 * 生成 src/lib/poi-photos.generated.ts（`城市::名称` → 本地路径）。
 *
 * 为什么只做 top240：全量 1178 张 ≈ 60MB+ 不可入库；240 张压缩后约 10MB，
 * 断网时全部「有人工描述的」POI 也有真图；其余 POI 保持 CDN 图 + 分类池降级。
 * 用法：node scripts/download-poi-photos.mjs（断点续跑，已有文件跳过）
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const OUT_DIR = path.resolve("public/spots/pois");
const GEN = path.resolve("src/lib/poi-photos.generated.ts");

const t = fs.readFileSync("src/lib/city-pois.generated.ts", "utf8");
const m = t.slice(t.indexOf("= {"));
const packs = eval("(" + m.slice(m.indexOf("{"), m.lastIndexOf(";")) + ")");

fs.mkdirSync(OUT_DIR, { recursive: true });
const map = {};
let ok = 0,
  fail = 0;

for (const [city, list] of Object.entries(packs)) {
  const top = [...list]
    .sort((a, b) => (b.rating || 0) - (a.rating || 0))
    .slice(0, 12);
  for (const p of top) {
    if (!p.image) continue;
    const key = `${city}::${p.name}`;
    const file = `${city}-${p.name}`.replace(/[\\/:*?"<>|\s]/g, "_") + ".webp";
    const out = path.join(OUT_DIR, file);
    if (!fs.existsSync(out)) {
      try {
        const res = await fetch(p.image, {
          signal: AbortSignal.timeout(20000),
        });
        if (!res.ok) throw new Error(`HTTP ${res.status}`);
        const buf = Buffer.from(await res.arrayBuffer());
        if (buf.length < 5000) throw new Error("too small");
        await sharp(buf)
          .resize({ width: 640, withoutEnlargement: true })
          .webp({ quality: 78 })
          .toFile(out);
      } catch (e) {
        fail++;
        console.log(`✗ ${key}: ${e.message}`);
        continue;
      }
    }
    map[key] = `/spots/pois/${encodeURIComponent(file)}`;
    ok++;
  }
}

const ts = `// GENERATED by scripts/download-poi-photos.mjs — top240 POI 本地首图（源：高德 CDN，构建时下载压缩）
// 不要手改；重跑 npm run pois:photos 重新生成。
export const POI_PHOTOS: Record<string, string> = ${JSON.stringify(map, null, 2)};
`;
fs.writeFileSync(GEN, ts, "utf8");
console.log(`\n${ok} 张本地化（${fail} 失败）→ public/spots/pois/`);
