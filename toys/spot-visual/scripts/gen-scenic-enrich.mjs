/**
 * A 级景区数据集接入：读 .cache/scenic.json（python 从官方 xlsx 转出，14844 条）
 * 1) 与城市包 POI 按「名称包含 + GCJ02 距离 < 500m」匹配 → 挂景区等级（5A/4A…）
 * 2) 27 城中未被任何库内景点覆盖的 3A+ 景区 → 反向补充为骨架景点
 * 产物：src/lib/scenic-enrich.generated.ts
 * 用法：先跑 python xlsx 转换（见 worklog 二十三轮），再 node scripts/gen-scenic-enrich.mjs
 */
import fs from "node:fs";
import path from "node:path";

const scenic = JSON.parse(fs.readFileSync(".cache/scenic.json", "utf8"));
const t = fs.readFileSync("src/lib/city-pois.generated.ts", "utf8");
const m = t.slice(t.indexOf("= {"));
const packs = eval("(" + m.slice(m.indexOf("{"), m.lastIndexOf(";")) + ")");

// 库内已有坐标点（POI + 手工景点坐标从 spot-data 提取太脆弱，POI 是主体；
// 手工 30 条按名称在 scenic 里精确匹配，匹配不到的坐标近似由 POI 覆盖兜底）
const dist2 = (a, b) => (a.lng - b.lng) ** 2 + (a.lat - b.lat) ** 2;
const DEG = 0.0045; // ≈500m

const scenicByCity = new Map();
for (const s of scenic) {
  const short = s.city.replace(/市$/, "");
  if (!scenicByCity.has(short)) scenicByCity.set(short, []);
  scenicByCity.get(short).push(s);
}

const LEVEL_RANK = { "5A": 5, "4A": 4, "3A": 3, "2A": 2, "1A": 1, A: 1 };

const poiLevels = {}; // `城市::POI名` -> level
const matchedScenic = new Set();
let matched = 0;

for (const [city, list] of Object.entries(packs)) {
  const cand = scenicByCity.get(city) ?? [];
  for (const p of list) {
    let best = null;
    for (const s of cand) {
      if (matchedScenic.has(s)) continue;
      // 名称包含关系（高德名常带后缀）或距离 < 500m
      const nameOk = s.name.includes(p.name) || p.name.includes(s.name);
      const near = dist2(s, p) < DEG * DEG;
      if (nameOk || near) {
        if (!best || LEVEL_RANK[s.level] > LEVEL_RANK[best.level]) best = s;
      }
    }
    if (best) {
      poiLevels[`${city}::${p.name}`] = best.level;
      matchedScenic.add(best);
      matched++;
    }
  }
}

// 反向补充：27 城中 3A+ 且未被匹配的景区
const extras = [];
const extraSeen = new Set();
for (const [city, cand] of scenicByCity) {
  if (!packs[city]) continue; // 只补已有城市包的城市
  for (const s of cand) {
    if (matchedScenic.has(s)) continue;
    if (LEVEL_RANK[s.level] < 3) continue;
    const key = city + "::" + s.name;
    if (extraSeen.has(key)) continue;
    extraSeen.add(key);
    matchedScenic.add(s);
    extras.push({
      name: s.name,
      city,
      address: [s.province === s.city ? "" : s.province, s.city, s.district, s.address]
        .filter(Boolean)
        .join(""),
      lng: s.lng,
      lat: s.lat,
      level: s.level,
    });
  }
}

const ts = `// GENERATED by scripts/gen-scenic-enrich.mjs — 2023 全国 A 级景区数据集（14844 条，来源 AtomGit Universal-Tool/de21c）
// 授权：仅供学习研究使用，非商业用途。不要手改。
export const SCENIC_LEVELS: Record<string, string> = ${JSON.stringify(poiLevels, null, 2)};

export interface ExtraScenic {
  name: string;
  city: string;
  address: string;
  lng: number;
  lat: number;
  level: string;
}

export const EXTRA_SCENICS: ExtraScenic[] = ${JSON.stringify(extras, null, 2)};
`;
fs.writeFileSync(path.resolve("src/lib/scenic-enrich.generated.ts"), ts, "utf8");
console.log(`POI 匹配等级: ${matched} | 反向补充 3A+: ${extras.length}`);
const lvCount = {};
for (const e of extras) lvCount[e.level] = (lvCount[e.level] || 0) + 1;
console.log("extras levels:", JSON.stringify(lvCount));
