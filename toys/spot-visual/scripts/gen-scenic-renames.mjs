/**
 * 生成景区名称映射：docs/outsource/out-name-fixes.final.json → src/lib/scenic-renames.ts
 *
 * 为什么单独一张表：A 级名录是 generated 数据（不要手改），清洗结果属于人工判断，
 * 分开放才能在重跑 fetch 脚本时不丢失，也便于审阅 diff。
 *
 * 用法：node scripts/gen-scenic-renames.mjs
 */
import fs from "node:fs";
import path from "node:path";

const SRC = path.resolve("docs/outsource/out-name-fixes.final.json");
const OUT = path.resolve("src/lib/scenic-renames.ts");

const data = JSON.parse(fs.readFileSync(SRC, "utf8"));
const renames = new Map(
  data.renames.map((r) => [r.from, r.to]).filter(([a, b]) => a !== b),
);
const drops = data.drops.map((d) => d.name);

// 防御：同一原名不得既改名又删除
for (const n of drops) {
  if (renames.has(n)) throw new Error(`同时出现在 renames 与 drops：${n}`);
}

const body = [...renames.entries()]
  .sort((a, b) => a[0].localeCompare(b[0], "zh"))
  .map(([from, to]) => `  ${JSON.stringify(from)}: ${JSON.stringify(to)},`)
  .join("\n");

const ts = `// GENERATED by scripts/gen-scenic-renames.mjs — 不要手改。
// 来源：docs/outsource/out-name-fixes.final.json（人工 + 大模型清洗，逐批验收）
// 作用：把《2023 年全国 A 级景区名录》里的脏名称规范化为可读名称，并剔除重复条目。
// 注意：取数键（照片/详情/描述）仍用原始名录名，这里只改展示名。

/** 原名 → 规范名（${renames.size} 条） */
export const SCENIC_RENAMES: Record<string, string> = {
${body}
};

/** 重复/非景区条目（公司名、管委会、长短名并存），共 ${drops.length} 条 */
export const SCENIC_DROPS: readonly string[] = ${JSON.stringify(drops, null, 2)} as const;

export const SCENIC_RENAMES_COUNT = ${renames.size};
export const SCENIC_DROPS_COUNT = ${drops.length};
`;

fs.writeFileSync(OUT, ts, "utf8");
console.log(`renames ${renames.size} / drops ${drops.length} → ${OUT}`);
