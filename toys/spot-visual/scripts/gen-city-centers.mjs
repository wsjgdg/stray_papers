/**
 * 生成全国城市中心坐标表：遍历 public/geo/<adcode>.json（DataV 市级 GeoJSON），
 * 取每个城市 feature 的 center/centroid（缺省用几何 bbox 中心），
 * 输出 src/lib/city-centers.generated.ts（原名 + 去「市/地区/自治州/盟」后缀的简称双键）。
 *
 * 用途：/api/osm 的地理编码本地化——城市名直接查表，替代国内不可达的 Nominatim。
 * 用法：node scripts/gen-city-centers.mjs（数据源更新后重跑）
 */
import fs from "node:fs";
import path from "node:path";

const GEO_DIR = path.resolve("public/geo");
const OUT = path.resolve("src/lib/city-centers.generated.ts");

const table = {}; // name -> [lng, lat]
let count = 0;

function bboxCenter(geometry) {
  let minX = Infinity,
    minY = Infinity,
    maxX = -Infinity,
    maxY = -Infinity;
  const walk = (c) => {
    if (typeof c[0] === "number") {
      if (c[0] < minX) minX = c[0];
      if (c[0] > maxX) maxX = c[0];
      if (c[1] < minY) minY = c[1];
      if (c[1] > maxY) maxY = c[1];
    } else c.forEach(walk);
  };
  walk(geometry.coordinates);
  if (!Number.isFinite(minX)) return null;
  return [(minX + maxX) / 2, (minY + maxY) / 2];
}

for (const file of fs.readdirSync(GEO_DIR).filter((f) => f.endsWith(".json"))) {
  const geo = JSON.parse(fs.readFileSync(path.join(GEO_DIR, file), "utf8"));
  for (const f of geo.features ?? []) {
    const full = f.properties?.name;
    if (!full) continue;
    let c = f.properties?.center ?? f.properties?.centroid;
    if (Array.isArray(c) && c.length >= 2) c = [Number(c[0]), Number(c[1])];
    else c = bboxCenter(f.geometry);
    if (!c || !Number.isFinite(c[0]) || !Number.isFinite(c[1])) continue;
    count++;
    table[full] = c;
    const short = full.replace(/(市|地区|自治州|盟|林区)$/, "");
    if (short !== full && !table[short]) table[short] = c;
  }
}

const ts = `// GENERATED by scripts/gen-city-centers.mjs — 全国城市中心坐标（源：public/geo DataV GeoJSON）
// 不要手改；数据源更新后重跑 npm run geo:centers 重新生成。
// 键含行政区划全称与去「市/地区/自治州/盟」简称两套；值为 [lng, lat]。
export const CITY_CENTERS: Record<string, [number, number]> = ${JSON.stringify(table, null, 2)};
`;
fs.writeFileSync(OUT, ts, "utf8");
console.log(`cities: ${count}, keys: ${Object.keys(table).length} → ${path.basename(OUT)}`);
