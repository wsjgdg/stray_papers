export interface DialogueLine {
  id: string;
  /** 说话的蛙；旁白用 "narration" */
  speakerId: FrogCharacterId | "narration";
  /** 台词正文 */
  text: string;
  /** 主角内心吐槽（可选，显示在台词下方小字） */
  innerVoice?: string;
  /** 真心话节点：好感过阈值时插入的 mask-off 台词（UI 显示小徽标） */
  heart?: boolean;
  /** 播放流跳转：本条播完后跳到该节点 id（分支段落末尾回主线用；缺省 = 顺序推进） */
  merge?: string;
  /** 二周目回响节点标记：由引擎在插入节点上打标（剧本文件不手写），View 据此显示「上学期」小徽标 */
  remember?: boolean;
  /** CG 定格（批次 B2）：本行展示时全屏定格淡入；纯演出，零数值语义；画面注册表在 src/data/cg.ts */
  cg?: string;
  /** 表情差分（批次 D1）：本行说话蛙的表情标注（旁白行忽略）；不标 = 引擎按沉默值 / 坦诚度档位自动选 */
  expression?: FrogExpression;
  /** 舞台背景（批次 J）：本行起切换舞台背景场景（注册表 src/components/play/StageBackground.tsx）；缺省 = 既有渐变氛围层，其他线不受影响 */
  bg?: string;
  /** 语音脚本标记（批次 T 起，P3 占位）：本行对应的语音条目名（缺省 = 行 id 本身）；当前不渲染，发布时按此清单录制 */
  voice?: string;
  /** 音效（批次 J）：进入本行时播放一次（注册表 src/lib/audio.ts 的 playSe）；同行只播一次 */
  se?: string;
  /** 线内切曲覆盖（批次 J）：本行起改播指定 BGM（曲库 src/lib/bgm.ts）；缺省按线映射或 bg 场景映射 */
  bgm?: string;
  /** 立绘姿势差分（批次 J）：本行说话蛙的姿势（stand 标准 / lean 探头倚靠 / hold 环抱）；缺省 stand */
  pose?: FrogPose;
  /** 服装差分（批次 J）：本行说话蛙显示查寝装备（手电+签到板，仅格格生效） */
  gear?: boolean;
}

/** 二周目回响：这只蛙记得你上一学期做过同一个选择（纯叙事，不改任何数值） */
export interface ChoiceEcho {
  text: string;
  speakerId: FrogCharacterId | "narration";
  innerVoice?: string;
}

export interface Choice {
  id: string;
  /** 选项文案（先好笑，后扎心） */
  text: string;
  /** 沉默值增量：+1~+3，越「识时务」越高 */
  silenceDelta: number;
  /** 好感关键选项：受益蛙（"all" = 本线出场的全体 NPC 蛙）；只在每线 2-4 个关键节点标注 */
  affinityTarget?: FrogCharacterId | "all";
  /** 好感变化量：+2~+5，个别「给玩家出口」的真话选项为 -2 */
  affinityDelta?: number;
  /** 真分支：选中后播放流跳到该节点 id（分支段落首节点；缺省 = 顺序推进） */
  branch?: string;
  /** 二周目回响台词：speakerId 必须是该选项场景里在场的蛙，或旁白（纯叙事） */
  echo?: ChoiceEcho;
  /** 岔路收束语：本学期走过这条支路时，结局卡「这学期你走过的岔路」区块里的一行（纯叙事，对三档结局都成立） */
  coda?: string;
  /** 沉默等待（批次 V）：选项浮层 30 秒无操作 → 自动走这个隐藏分支（无提示无倒计时；被注意值 +1）。
   *  只在个别关键节点配置——教学线第一张表、湖边意义之问。设置里可关。 */
  idle?: { text: string; innerVoice?: string; silenceDelta: number };
  /** 行政语言翻译对（批次 Y·题材实验一）：同组选项共用的双栏文本——左「行政版」右「真实版」。
   *  两组文本同时存在，看哪边是玩家的决定：选行政版（+沉默）或看真实版（收进真话罐）。 */
  translatorPair?: { officialese: string; truth: string };
}

export interface Scene {
  id: string;
  lines: DialogueLine[];
  /** 本场景收尾的选项（每幕 2~3 个） */
  choices?: Choice[];
}

export interface Act {
  id: string;
  /** 第几幕，从 1 开始 */
  index: number;
  title: string;
  scenes: Scene[];
  /** 幕尾「蛙言蛙语」：本幕金句 */
  quote?: string;
  /** 金句出自谁（角色 id 或旁白） */
  quoteBy?: FrogCharacterId | "narration";
}

export interface Ending {
  id: string;
  title: string;
  text: string;
  /** 命中该结局的沉默值区间（闭区间，可缺省）。常规线标准三档 0-4 / 5-12 / 13+；
   *  行政楼线自批次 CY-124 起为 0-4 / 5-14 / 15+（第四幕抬高了本线沉默上限，高档门槛随之上调）；
   *  湖边终章宽档 0-10 / 11-24 / 25+ */
  minSilence?: number;
  maxSilence?: number;
  /** 二周目专属尾段（档案补记）：playthrough ≥ 2 时在结局卡追加；锚定「第二学期」本身，不依赖「这是你第二次走到该结局」 */
  plus?: string;
  /** 三周目免检批注（第三学期）：playthrough ≥ 3 时在档案补记之下追加；档案腔，比补记更干燥——连「记得」这道手续也按惯例免了 */
  thirdNote?: string;
  /**
   * 私档（批次 BV）：这一档的前提是「不知道」。调阅过本线主蛙的私档之后，这一档永久关闭——
   * 「不知道」的那个版本回不去了，你成了知道的那只蛙。
   */
  forbidTrace?: boolean;
  /**
   * 处置单（批次 CY-124 结算画面）：结局卡标题下方的档位结算块——
   * 印章 + 档位名 + 认定依据（累计沉默值落进哪一档）+ 一行档案判词 + 每档一幅小定格。
   * 缺省不渲染；目前只有行政楼线三档配了（画面在 components/play/EndingSettlementPlate.tsx）。
   */
  settlement?: {
    /** 印章大字（红框，落在判词右上角） */
    stamp: string;
    /** 档位名（真话档 / 转述档 / 沉默档） */
    tierName: string;
    /** 一行档案判词 */
    caption: string;
    /** 定格意象三连（批次 CY-125 全线铺开后新增）：零件名取自 EndingSettlementPlate 的零件库；
     *  行政楼线三档走专属定格，不配此字段 */
    art?: [string, string, string];
  };
}

export interface StoryScript {
  lineId: StorylineId;
  acts: Act[];
  endings: Ending[];
  /** 结局定格（批次 J）：线级结局 CG，结局相位在结局卡展示（三档共用）；缺省不显示 */
  endingCg?: string;
  /** 二周目记忆锚点段：playthrough ≥ 2 时在锚点行节点之后插入整段（纯叙事，锚点须在线性主推进路径上、不带 merge、非 heart 节点） */
  resonances?: Array<{
    afterId: string;
    lines: Array<{ speakerId: FrogCharacterId | "narration"; text: string; innerVoice?: string }>;
  }>;
}

