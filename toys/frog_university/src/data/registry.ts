/** 你抽屉里的页数（批次 DL）：编外宇宙最新计数 */
export function unregisteredCountOf(save: GameSaveData): number {
  let count = 0;
  if ((save.noteLog ?? []).length > 0) count += 1;
  if ((save.destructionLog ?? []).some((item) => item.pick === "copy")) count += 1;
  if ((save.selfEntryLog ?? []).some((item) => item.pick === "retained")) count += 1;
  if ((save.selfEntryLog ?? []).some((item) => item.pick === "filed")) count += 1;
  return Math.max(1, count);
}

