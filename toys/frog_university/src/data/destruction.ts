/** 清册上的「你的那一行」（批次 DB）：这学期受理过哪张纸，焚化的就是它 */
export function destructionItemLine(save: GameSaveData): string {
  const semester = save.playthrough;
  const has = (log: { semester: number }[] | undefined): boolean =>
    (log ?? []).some((item) => item.semester === semester);
  if (has(save.testimonyLog)) return "核对通知原件（受理完毕）：一页——你的";
  if (has(save.lostPageLog)) return "补述笔录受理回执（办结）：一页——你的";
  if (has(save.misdeliveryLog)) return "处分决定书誊写底稿（已复核）：一页——你的";
  if (has(save.mergerLog)) return "合并通知书退件存根：一页——你的";
  if (has(save.transitLog)) return "转递交接单封缄联（已启封）：一页——你的";
  return "过期回执（年度清理）：一页——你的";
}

