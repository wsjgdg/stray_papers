/** 补记的那一张纸（批次 DE）：抽屉里哪张没编号的纸，这一批就补记它 */
export function selfEntryTargetOf(save: GameSaveData): { label: string; hint: string } {
  const semester = save.playthrough;
  if ((save.noteLog ?? []).some((item) => item.semester === semester)) {
    return { label: "信格里那张没编号的便条", hint: "（没有编号——这是补记的第一道坎）" };
  }
  if ((save.destructionLog ?? []).some((item) => item.semester === semester && item.pick === "copy")) {
    return { label: "你抄过的那张抄件", hint: "（原件已焚化——抄的那份没有编号）" };
  }
  if ((save.bereadLog ?? []).some((item) => item.semester === semester)) {
    return { label: "那张不应当存在的知会单", hint: "（按规定不应当存在——但存在过）" };
  }
  return { label: "一件它们没记过的事", hint: "（你记得它发生过）" };
}

