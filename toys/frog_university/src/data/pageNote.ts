/** 页边上的那一个字，落在哪一页（批次 DJ）：按本学期顶班的处理派生 */
export function pageNoteWhereOf(save: GameSaveData): string {
  const semester = save.playthrough;
  const record = (save.substituteLog ?? []).find((item) => item.semester === semester);
  if (record?.pick === "sign") return "你留名的那行旁边";
  if (record?.pick === "serve") return "那一天的空白旁边";
  if (record?.pick === "refuse") return "那一天的空班记录旁边";
  return "页边";
}

