/** 你抽屉里的东西（批次 DG）：编外宇宙的最新清单，按历史记录派生 */
export function declarationItemsOf(save: GameSaveData): string[] {
  const items: string[] = [];
  if ((save.noteLog ?? []).length > 0) items.push("无编号便条一张（未归档）");
  if ((save.destructionLog ?? []).some((item) => item.pick === "copy")) {
    items.push("焚化抄件一页（无存根）");
  }
  if ((save.selfEntryLog ?? []).some((item) => item.pick === "retained")) {
    items.push("退回的补记申请一页（格式不符）");
  }
  if ((save.selfEntryLog ?? []).some((item) => item.pick === "filed")) {
    items.push("自记号 036-ZJ-001 原件一页（编外保管）");
  }
  if (items.length === 0) items.push("一件你一直收着的东西（申报时由你描述）");
  return items;
}

