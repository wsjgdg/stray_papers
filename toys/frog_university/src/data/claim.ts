/** 清单上你的那一行（批次 DN）：挂失过的那件，或者历届失物 */
export function claimItemOf(save: GameSaveData): { label: string; hint: string } {
  const semester = save.playthrough;
  if ((save.overdueLog ?? []).some((item) => item.semester === semester && item.pick === "lose")) {
    return { label: "挂失的那件（你收着的那页）", hint: "（失物清单上有它的编号——它一直在你抽屉里）" };
  }
  return { label: "历届失物一件（编号不详）", hint: "（清单上没有描述——失物不记形状）" };
}

