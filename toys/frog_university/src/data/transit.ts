/** 转递的去向（批次 CW）：按种子派生 */
export function transitDestinationOf(seed: number): { office: string; reason: string } {
  const base = Math.round(seed) % 1000000;
  const offices = ["学工办", "校务办", "学籍管理科", "学生资助中心"];
  const reasons = ["例行复核", "权限变更", "年度抽查", "跨部门协查"];
  const office = offices[Math.floor(seedRandom(base * 1523 + 317) * offices.length) % offices.length] ?? offices[0] ?? "学工办";
  const reason = reasons[Math.floor(seedRandom(base * 1543 + 331) * reasons.length) % reasons.length] ?? reasons[0] ?? "例行复核";
  return { office, reason };
}

