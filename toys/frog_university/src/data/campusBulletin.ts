/**
 * 按天取今日公告：确定性——同一局同一天恒定，不同局序列不同。
 * finalWeek 时整池换成期末公告（与深夜事件、天色的换法一致）。
 */
export function bulletinForDay(day: number, seed = 0, finalWeek = false): string {
  const pool = finalWeek ? FINAL_BULLETINS : BULLETINS;
  const roll = seedRandom((Math.round(seed) % 1000000) * 17 + Math.round(day) * 101);
  return pool[Math.floor(roll * pool.length) % pool.length];
}
