/** 求你顶班的那一只（批次 DI）：按种子派生 */
export function substitutePeerOf(seed: number): string {
  const pool = (Object.values(FROG_CHARACTERS) as { id: string; displayName: string }[]).filter(
    (item) => item.id !== "naiBai",
  );
  const hit =
    pool[Math.floor(seedRandom((Math.round(seed) % 1000000) * 1823 + 461) * pool.length) % pool.length];
  return hit?.displayName ?? "隔壁班那只";
}

