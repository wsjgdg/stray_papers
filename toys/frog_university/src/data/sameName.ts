/** 用你名字的那一只（批次 DR）：按种子派生 */
export function sameNamePeerOf(seed: number): string {
  const pool = (Object.values(FROG_CHARACTERS) as { id: string; displayName: string }[]).filter(
    (item) => item.id !== "naiBai",
  );
  const hit =
    pool[Math.floor(seedRandom((Math.round(seed) % 1000000) * 1997 + 587) * pool.length) % pool.length];
  return hit?.displayName ?? "名册另一页那只";
}

