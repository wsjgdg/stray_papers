/** 摘要里那宗卷宗的主人（批次 DH）：按种子派生 */
export function openDayPeerOf(seed: number): string {
  const pool = (Object.values(FROG_CHARACTERS) as { id: string; displayName: string }[]).filter(
    (item) => item.id !== "naiBai",
  );
  const hit =
    pool[Math.floor(seedRandom((Math.round(seed) % 1000000) * 1811 + 457) * pool.length) % pool.length];
  return hit?.displayName ?? "名册另一页那只";
}

