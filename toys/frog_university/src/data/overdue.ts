/** 挂账的那一件（批次 DF）：你编外宇宙里最新的一张纸，这次被点名了 */
export function overdueItemOf(save: GameSaveData): { label: string; hint: string } {
  const semester = save.playthrough;
  const has = (log: { semester: number; pick?: string }[] | undefined, pick?: string): boolean =>
    (log ?? []).some((item) => item.semester === semester && (pick ? item.pick === pick : true));
  if (has(save.selfEntryLog, "retained")) {
    return { label: "退回的补记申请一页", hint: "（格式不符——它想进台账，台账不收）" };
  }
  if (has(save.selfEntryLog, "filed")) {
    return { label: "自记号 036-ZJ-001（原件在本人处）", hint: "（编外——原件没进柜子）" };
  }
  if (has(save.destructionLog, "copy")) {
    return { label: "焚化抄件一页", hint: "（无存根——它只属于知道有它的那一只蛙）" };
  }
  if (has(save.noteLog)) {
    return { label: "无编号便条一张", hint: "（未归档——它从来没有进过档案）" };
  }
  return { label: "上学期结转事项一项", hint: "（结转的意思是：它跟着你来了新学期）" };
}

