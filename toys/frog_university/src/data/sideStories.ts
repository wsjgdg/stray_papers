import type { FrogCharacterId } from "@/data/characters";

export interface SideStoryNode {
  id: string;
  speakerId: FrogCharacterId | "narration";
  text: string;
  /** 主角内心（可选，仅台词行生效） */
  innerVoice?: string;
}

export interface SideStoryChoice {
  id: string;
  text: string;
  /** 0 = 真话出口（首看入真话罐）；+1 = 沉默（首看沉默值 +1）——重看不计数 */
  silenceDelta: number;
  /** 选完之后的收束旁白 */
  coda: string;
}

export interface SideStory {
  id: string;
  /** 讲这集番外的那只蛙 */
  frogId: FrogCharacterId;
  title: string;
  /** 地点与时刻（播放器顶部小注） */
  place: string;
  /** 名册按钮上的一句话预告 */
  hint: string;
  /** 定格插画（CY-133）：这一集的开场画面（注册表在 src/components/play/CgArt.tsx 的 CG_ART）；
   *  不进 CG_SCENES——番外属于好感名册，不算剧情定格的分母 */
  cg?: string;
  nodes: SideStoryNode[];
  /** 收尾两支（真话 / 沉默），口径同深夜事件 */
  choices: SideStoryChoice[];
  /** 收束后的档案行 */
  archive: string;
}

