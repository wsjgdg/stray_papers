/** 差异的那一行（批次 DD）：本学期办过哪件事，对出来的差异就长在哪件事上 */
export function reconciliationDiscrepancyOf(save: GameSaveData): string {
  const semester = save.playthrough;
  const has = (log: { semester: number }[] | undefined): boolean =>
    (log ?? []).some((item) => item.semester === semester);
  if (has(save.bereadLog))
    return "差异一处：调阅知会——台账有调阅记录，柜中无存根（该单按规定不应当存在）。";
  if (has(save.lostPageLog))
    return "差异一处：补页受理回执——台账记载在册，柜中无原件（原件遗失，已由当事人补述）。";
  if (has(save.misdeliveryLog))
    return "差异一处：处分决定书誊写底稿——台账记载在册，柜中无底稿（已按误投退回）。";
  if (has(save.transitLog))
    return "差异一处：转递交接单封缄联——台账记载已启封，柜中无封缄联（启封时已销毁）。";
  if (has(save.mergerLog))
    return "差异一处：合并通知书的退件存根——台账记载在册，柜中无存根（合并后按合宗计）。";
  return "差异一处：学期手册发放——台账记载已发，柜中无原件（按规程，已发的不再补发）。";
}

