/** 下一学期开学挂在档案上的小字（批次 DP） */
export function letterBoxKeptLine(): string {
  return "（信格通了一回。它给的那个口，开没开、开多宽，都是你定的。）";
}

/** 信格现状（批次 DP）：按本学期的编外痕迹描述 */
export function letterBoxStateOf(save: GameSaveData): string {
  const semester = save.playthrough;
  if ((save.noteLog ?? []).some((item) => item.semester === semester)) {
    return "信格里有一张没编号的纸（等取）";
  }
  if ((save.bereadLog ?? []).some((item) => item.semester === semester)) {
    return "信格来过一张不该存在的知会单";
  }
  return "信格照常收信";
}
