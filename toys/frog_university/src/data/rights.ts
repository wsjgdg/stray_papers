/** 下一学期开学挂在档案上的小字（批次 DC） */
export function rightsKeptLine(): string {
  return "（权利告知书送达过一次。你的权利是有的——用没用过，卷里记着。）";
}

/** 告知书的注脚开关（批次 DC）：本学期被调阅过，第三条的注脚才亮 */
export function hasBereadOfThisSemester(save: GameSaveData): boolean {
  return (save.bereadLog ?? []).some((item) => item.semester === save.playthrough);
}
