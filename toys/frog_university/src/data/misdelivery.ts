/** 误投决定书的落点（批次 CS）：按种子取一件你没干过的事 */
export function misdeliveryNoticeOf(seed: number): { violation: string; when: string } {
  const base = Math.round(seed) % 1000000;
  const violation = MISDELIVERY_VIOLATIONS[Math.floor(seedRandom(base * 1409 + 277) * MISDELIVERY_VIOLATIONS.length) % MISDELIVERY_VIOLATIONS.length] ?? MISDELIVERY_VIOLATIONS[0] ?? "（事由栏空白。）";
  const week = 3 + Math.floor(seedRandom(base * 1423 + 281) * 9);
  return { violation, when: `本学期第 ${week} 周` };
}

